@api_bp.route('/log', methods=['POST'])
def trmnl_log_api():
    auth_error = _authorize_trmnl_request(allow_signed_query=False)
    if auth_error is not None:
        return auth_error

    if request.content_length is not None and request.content_length > MAX_TRMNL_LOG_BYTES:
        return jsonify({"error": f"Log payload exceeds maximum size of {MAX_TRMNL_LOG_BYTES} bytes."}), 413

    raw_body = request.get_data(cache=True, as_text=False)
    if len(raw_body) > MAX_TRMNL_LOG_BYTES:
        return jsonify({"error": f"Log payload exceeds maximum size of {MAX_TRMNL_LOG_BYTES} bytes."}), 413

    log_data = None
    if raw_body:
        try:
            log_data = json.loads(raw_body.decode('utf-8'))
        except (ValueError, UnicodeDecodeError):
            form_data = request.form.to_dict()
            log_data = form_data if form_data else raw_body.decode('utf-8', errors='ignore')
    else:
        log_data = request.form.to_dict() or ''

    record_trmnl_log_message(dict(request.headers), log_data)
    return jsonify({"status": 200})


