def _is_mac_allowed(trmnl_cfg):
    allowed = trmnl_cfg.get('allowed_macs')
    if not allowed:
        return True
    if isinstance(allowed, str):
        allowed = [allowed]
    normalized_allowed = {str(mac).strip().upper() for mac in allowed if str(mac).strip()}
    if not normalized_allowed:
        return True
    device_mac = (request.headers.get('ID') or request.headers.get('Id') or '').strip().upper()
    if not device_mac:
        return False
    return any(hmac.compare_digest(device_mac, candidate) for candidate in normalized_allowed)


@api_bp.route('/setup', methods=['GET'])
def trmnl_setup_api():
    config = load_config()
    trmnl_cfg = config.get('trmnl') or {}
    api_key = _get_trmnl_api_key(config)

    authenticated = _is_valid_access_token(api_key)
    if not authenticated:
        if not bool(trmnl_cfg.get('setup_enabled', False)):
            return jsonify({"error": "TRMNL setup endpoint is disabled."}), 403
        if not _is_mac_allowed(trmnl_cfg):
            return jsonify({"error": "Device MAC address is not authorized for setup."}), 403

    if not api_key:
        return jsonify({"error": "TRMNL API key is not configured."}), 503

    refresh_rate = int(trmnl_cfg.get('refresh_rate_seconds', 600))
    base_url = get_request_base_url()
    image_url = _build_signed_image_url(base_url, '/api/display/current.bmp', api_key, refresh_rate * 2)
    return jsonify({
        "status": 200,
        "api_key": api_key,
        "friendly_id": "TRMNL-SOLAR",
        "image_url": image_url,
        "filename": "solar_setup.bmp",
        "message": "TRMNL connected to Enphase solar dashboard"
    })


@api_bp.route('/display', methods=['GET'])
def trmnl_display_api():
    config = load_config()
    auth_error = _authorize_trmnl_request(config, allow_signed_query=False)
    if auth_error is not None:
        return auth_error

    trmnl_cfg = config.get('trmnl') or {}
    api_key = _get_trmnl_api_key(config)
    refresh_rate = int(trmnl_cfg.get('refresh_rate_seconds', 600))
    base_url = get_request_base_url()

    record_trmnl_checkin(dict(request.headers))

    bmp_path = trmnl_service.OUTPUT_BMP_PATH
    if not os.path.exists(bmp_path):
        update_trmnl_display(current_app._get_current_object())

    # TRMNL firmware uses filename comparison to skip refresh if unchanged.
    # Appending mtime ensures TRMNL detects when a new render is available.
    mtime = int(os.path.getmtime(bmp_path)) if os.path.exists(bmp_path) else int(time.time())
    filename = f"solar_{mtime}.bmp"
    image_url = _build_signed_image_url(base_url, '/api/display/current.bmp', api_key, refresh_rate * 2)

    return jsonify({
        "status": 0,
        "image_url": image_url,
        "filename": filename,
        "refresh_rate": refresh_rate,
        "reset_firmware": False,
        "update_firmware": False,
        "firmware_url": None,
        "special_function": "none",
        "image_rotate": 1
    })


