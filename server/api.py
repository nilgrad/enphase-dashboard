MAX_TRMNL_LOG_BYTES = 16 * 1024  # 16 KiB max payload for POST /api/log
DEFAULT_REFRESH_COOLDOWN_SECONDS = 30.0
MIN_SIGNED_IMAGE_TTL_SECONDS = 300

_refresh_lock = threading.Lock()
_refresh_in_progress = False
_last_refresh_monotonic = None


def reset_refresh_cooldown():
    """Reset the /api/history/refresh rate-limit state (useful in tests)."""
    global _refresh_in_progress, _last_refresh_monotonic
    with _refresh_lock:
        _refresh_in_progress = False
        _last_refresh_monotonic = None


def get_request_base_url():
    """Return the request base URL derived from WSGI (safe with optional ProxyFix)."""
    return request.url_root.rstrip('/')


def _get_trmnl_api_key(config=None):
    """Resolve the configured TRMNL API key from environment or config.yml (no insecure default)."""
    env_key = os.environ.get('TRMNL_API_KEY')
    if isinstance(env_key, str) and env_key.strip():
        return env_key.strip()
    if config is None:
        config = load_config()
    trmnl_cfg = config.get('trmnl') or {}
    key = trmnl_cfg.get('api_key')
    if isinstance(key, str) and key.strip():
        return key.strip()
    return None


def _is_valid_access_token(expected_key):
    """Constant-time check of the incoming Access-Token header against the configured key."""
    if not expected_key:
        return False
    provided = request.headers.get('Access-Token')
    if not provided:
        return False
    return hmac.compare_digest(provided.strip(), expected_key)


def _compute_image_signature(api_key, path, expires_at):
    payload = f"{path}:{int(expires_at)}".encode('utf-8')
    return hmac.new(api_key.encode('utf-8'), payload, hashlib.sha256).hexdigest()


def _build_signed_image_url(base_url, path, api_key, ttl_seconds):
    expires_at = int(time.time()) + max(int(ttl_seconds), MIN_SIGNED_IMAGE_TTL_SECONDS)
    sig = _compute_image_signature(api_key, path, expires_at)
    query = urlencode({'exp': expires_at, 'sig': sig})
    return f"{base_url}{path}?{query}"


def _is_valid_signed_image_request(expected_key):
    """Verify a short-lived HMAC query signature generated by /api/display or /api/setup."""
    if not expected_key:
        return False
    exp_raw = request.args.get('exp')
    sig = request.args.get('sig')
    if not exp_raw or not sig:
        return False
    try:
        expires_at = int(exp_raw)
    except ValueError:
        return False
    if expires_at < int(time.time()):
        return False
    expected_sig = _compute_image_signature(expected_key, request.path, expires_at)
    return hmac.compare_digest(sig, expected_sig)


def _authorize_trmnl_request(config=None, allow_signed_query=False):
    """Validate TRMNL authentication; returns None if authorized, else a (response, 401) tuple."""
    expected_key = _get_trmnl_api_key(config)
    if _is_valid_access_token(expected_key):
        return None
    if allow_signed_query and _is_valid_signed_image_request(expected_key):
        return None
    return jsonify({"error": "Unauthorized"}), 401


def _handle_gateway_error(endpoint_name, exc):
    """Log full traceback server-side and return a sanitized error response with proper status."""
    logger.exception("Enphase Gateway error in %s", endpoint_name)
    if isinstance(exc, requests.exceptions.Timeout):
        return jsonify({"error": "Enphase Gateway request timed out."}), 504
    if isinstance(exc, requests.exceptions.HTTPError):
        status = exc.response.status_code if exc.response is not None else None
        if status in (401, 403):
            return jsonify({"error": "Authentication with Enphase Gateway failed."}), 502
        return jsonify({"error": "Enphase Gateway returned an error response."}), 502
    if isinstance(exc, requests.exceptions.RequestException):
        return jsonify({"error": "Unable to connect to Enphase Gateway."}), 502
    if isinstance(exc, (json.JSONDecodeError, ValueError)):
        return jsonify({"error": "Received invalid response from Enphase Gateway."}), 502
    return jsonify({"error": "An internal server error occurred."}), 500


def _handle_internal_error(endpoint_name, exc):
    """Log full traceback server-side and return a generic 500 error without leaking internals."""
    logger.exception("Internal server error in %s", endpoint_name)
    return jsonify({"error": "An internal server error occurred."}), 500


